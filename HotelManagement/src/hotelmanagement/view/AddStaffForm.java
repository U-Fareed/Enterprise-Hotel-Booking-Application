    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
    String user = usernameInput.getText().trim();
    String pass = new String(passwordInput.getPassword()).trim();
    String name = fullNameInput.getText().trim();
    String role = roleInput.getSelectedItem().toString();
    boolean active = activeCheck.isSelected();

    hotelmanagement.controller.StaffController.StaffResult result =
            new hotelmanagement.controller.StaffController().saveStaff(
                    editingStaff != null ? editingStaff.getStaffId() : null,
                    user, pass, name, role, active);

    javax.swing.JOptionPane.showMessageDialog(this, result.message);
    if (result.success) {
        new StaffControls().setVisible(true);
        this.dispose();
    }
    }//GEN-LAST:event_saveBtnActionPerformed

